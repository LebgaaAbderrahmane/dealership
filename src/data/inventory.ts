function toVehicle(e: InventoryEntry): Vehicle {
  const featureCount = 6 + (e.id % 5);
  const features = Array.from(new Set(Array.from({ length: featureCount }, (_, k) => FEATURES[(e.id + k * 3) % FEATURES.length])));
  return {
    id: e.id,
    year: e.year,
    name: e.name,
    type: e.type,
    make: e.make,
    price: e.price,
    monthly: e.monthly,
    miles: e.miles,
    drivetrain: e.drivetrain,
    badge: e.badge,
    image: img(e.imageId),
    transmission: e.transmission,
    fuel: e.fuel,
    color: e.color,
    mpg: e.mpg,
    features,
    gallery: e.galleryIds.map((id) => img(id)),
    stock: `APX${10000 + e.id * 7}`,
    description: e.engine,
    engine: e.engine,
    horsepower: e.horsepower,
    torque: e.torque,
    acceleration: e.acceleration,
    topSpeed: e.topSpeed,
    seats: e.seats,
    doors: e.doors,
    cargoVolume: e.cargoVolume,
    batteryCapacity: e.batteryCapacity,
    range: e.range,
    towingCapacity: e.towingCapacity,
  };
}

export const inventory: Vehicle[] = INVENTORY.map(toVehicle);

export const VEHICLE_COUNT = inventory.length;

export function getVehicleById(id: number | string | undefined) {
  if (id === undefined) return undefined;
  const n = Number(id);
  return inventory.find((v) => v.id === n);
}

export function similarVehicles(vehicle: Vehicle, count = 3) {
  return inventory
    .filter((v) => v.id !== vehicle.id)
    .sort((a, b) => {
      const aScore = (a.type === vehicle.type ? 0 : 1) + (a.make === vehicle.make ? 0 : 1) + Math.abs(a.price - vehicle.price) / 10000;
      const bScore = (b.type === vehicle.type ? 0 : 1) + (b.make === vehicle.make ? 0 : 1) + Math.abs(b.price - vehicle.price) / 10000;
      return aScore - bScore;
    })
    .slice(0, count);
}
